#!/usr/bin/env python3
"""Score the sensor against the lab ground truth and write docs/EVALUATION.md.

    python eval/evaluate.py --results lab_results [--config config.json] [--soak lab_results/soak.pcap]

Needs tshark (it replays each PCAP through the real pyshark pipeline). Re-running is deterministic.
"""
import argparse
import json
import sys
import warnings
from datetime import datetime
from pathlib import Path

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from ids.capture import CaptureSession  # noqa: E402
from ids.engine import NullSink, PacketAnalyzer  # noqa: E402
from ids.settings import Settings  # noqa: E402


class Collect(NullSink):
    def __init__(self):
        self.alerts = {}

    def on_alert(self, kind, alert):
        self.alerts[alert["id"]] = alert           # keep the latest snapshot of each alert


def analyze(pcap: Path, config: dict):
    sink = Collect()
    analyzer = PacketAnalyzer(config, sink)
    CaptureSession(analyzer, pcap_path=pcap).run()
    analyzer.flush()
    return sink, analyzer


def md(text) -> str:
    return str(text).replace("|", "\\|")


def load_baselines(results: Path, name: str) -> dict:
    f = results / "baselines" / f"{name}.json"
    return json.loads(f.read_text()) if f.exists() else {}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="lab_results")
    ap.add_argument("--config", default=str(ROOT / "tests" / "fixtures" / "config.json"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "EVALUATION.md"))
    ap.add_argument("--notes", default=str(Path(__file__).resolve().parent / "NOTES.md"))
    ap.add_argument("--soak", default=None, help="long benign capture to measure false positives per hour")
    args = ap.parse_args()

    results = Path(args.results)
    settings = Settings(Path(args.config))
    config = settings.analyzer_config()
    info = json.loads((results / "lab_info.json").read_text()) if (results / "lab_info.json").exists() else {}
    truth = [json.loads(line) for line in (results / "ground_truth.jsonl").read_text().splitlines() if line.strip()]
    has_baselines = any((results / "baselines" / f"{t['name']}.json").exists() for t in truth)

    evaluated = []
    for rec in truth:
        pcap = results / rec["pcap"]
        print(f"analysing {rec['name']} ...", flush=True)
        sink, analyzer = analyze(pcap, config)
        alerts = sorted(sink.alerts.values(), key=lambda a: a["first_seen"])
        outcomes = {a["outcome"] for a in alerts}
        expect = set(rec["expect"])
        hits = [a for a in alerts if a["outcome"] in expect]
        first = min((datetime.fromisoformat(a["first_seen"]).timestamp() - rec["t_start"] for a in hits), default=None)
        if rec["kind"] == "attack":
            if hits:
                verdict = "detected" + (f" (+ {', '.join(sorted(outcomes - expect))})" if outcomes - expect else "")
            else:
                verdict = "missed (expected)" if rec.get("known_limitation") else "**MISSED**"
        else:
            verdict = "clean" if not alerts else f"**FALSE POSITIVE** ({', '.join(sorted(outcomes))})"
        ev = dict(rec, outcomes=sorted(outcomes), n_alerts=len(alerts), first_alert_s=first, verdict=verdict,
                  packets=analyzer.packets_processed, baselines=load_baselines(results, rec["name"]))
        evaluated.append(ev)

    # ---- summary numbers -----------------------------------------------------------
    attacks = [e for e in evaluated if e["kind"] == "attack"]
    benign = [e for e in evaluated if e["kind"] == "benign"]
    detected = [e for e in attacks if e["verdict"].startswith("detected")]
    must = [e for e in attacks if not e.get("known_limitation")]
    must_hit = [e for e in must if e["verdict"].startswith("detected")]
    wrong_type = [e for e in detected if "+" in e["verdict"]]
    fps = [e for e in benign if e["verdict"] != "clean"]

    lines = ["# Evaluation: real attack tools against the sensor", "",
             f"_Generated by `eval/evaluate.py` on {datetime.now():%Y-%m-%d}. Do not edit by hand: re-run it._", "",
             "## Summary", "",
             f"- **Attack scenarios detected:** {len(must_hit)}/{len(must)} (scenarios without a documented limitation); "
             f"{len(detected)}/{len(attacks)} counting the documented limitations too",
             f"- **Benign scenarios with no alert:** {len(benign) - len(fps)}/{len(benign)}",
             "- **Alerts per detected attack:** "
             + (f"{sum(e['n_alerts'] for e in detected) / len(detected):.1f} (aggregation: 1.0 is ideal)" if detected else "n/a"),
             f"- **Attack runs that also raised an unexpected alert type:** {len(wrong_type)}", ""]

    head = "| Scenario | Command | Expected | Raised | Alerts | First alert | Verdict |"
    sep = "|---|---|---|---|---|---|---|"
    if has_baselines:
        head += " Zeek | Suricata |"
        sep += "---|---|"
    lines += ["## Results", "", head, sep]
    for e in evaluated:
        cmd = e["cmd"] if len(e["cmd"]) <= 58 else e["cmd"][:55] + "..."
        first = f"{e['first_alert_s']:.1f} s" if e["first_alert_s"] is not None else "-"
        row = (f"| {e['name']} | `{md(cmd)}` | {', '.join(e['expect']) or '-'} | {', '.join(e['outcomes']) or '-'} "
               f"| {e['n_alerts']} | {first} | {e['verdict']} |")
        if has_baselines:
            b = e["baselines"]
            z = ", ".join(sorted(set(b.get("zeek", {}).get("notices", [])))) or ("-" if "zeek" in b else "n/a")
            s = (str(len(b["suricata"]["alerts"])) + " alerts") if "suricata" in b else "n/a"
            row += f" {md(z)} | {s} |"
        lines.append(row)

    notes = [f"- `{e['name']}` was missed: {e.get('known_limitation') or 'UNEXPECTED, investigate'}"
             for e in attacks if not e["verdict"].startswith("detected")]
    notes += [f"- `{e['name']}` also raised: {e['verdict'].split('(+')[1].rstrip(')')}" for e in wrong_type]
    notes += [f"- `{e['name']}` raised a false positive: {', '.join(e['outcomes'])}" for e in fps]
    lines += ["", "## Misses and surprises", ""] + (notes or ["- none"])

    if args.soak:
        sink, analyzer = analyze(Path(args.soak), config)
        hours = max((analyzer.last_packet_ts - analyzer.first_packet_ts) / 3600, 1e-9)
        lines += ["", "## Benign soak (false positives per hour)", "",
                  f"- Capture: `{Path(args.soak).name}`, {hours * 60:.1f} minutes, {analyzer.packets_processed} packets, "
                  f"{analyzer.flows_closed} flows",
                  f"- Alerts: **{len(sink.alerts)}** ({len(sink.alerts) / hours:.2f} per hour)"]
        for a in sink.alerts.values():
            lines.append(f"  - {a['first_seen']} `{a['outcome']}` {a['src_ip']} -> {a['dst_ip']} ({'; '.join(a.get('reasons', []))[:120]})")

    det = config.get("detection", {})
    lines += ["", "## Settings used", "",
              "| setting | value |", "|---|---|"] + [f"| {k} | {det[k]} |" for k in (
                  "match_threshold", "half_open_min_count", "half_open_grace_seconds", "portsweep_port_threshold",
                  "ipsweep_host_threshold", "recon_window_seconds", "alert_cooldown_seconds") if k in det]
    tools = "".join(f"\n  - {t}: {v}" for t, v in (info.get("tools") or {}).items())
    lines += ["", "## Method", "",
              f"- **Lab:** attacker `{info.get('attacker', '?')}` -> victim `{info.get('victim', '?')}`; run on {info.get('date', '?')}; "
              f"{info.get('kernel', '')}; tool versions:{tools}",
              "- **Capture point:** `tcpdump` on the attacker's lab interface, one PCAP per scenario. Each PCAP is replayed through the "
              "real pyshark/tshark pipeline, with a fresh analyzer per scenario.",
              "- **Ground truth:** `run_lab.py` records the command, its start/end time and the detectors it should trigger. "
              "*Detected* means at least one alert of an expected type; *first alert* is measured from the command's start.",
              "- **Background traffic:** one ping per second to the victim runs throughout, standing in for the traffic a real network always "
              "has. The sensor's clock is packet-driven, so a probe that has to outlive the half-open grace period is only declared failed "
              "once a later packet arrives.",
              "- **Host sweeps:** on a flat Ethernet segment, probes to dead hosts stop at ARP and never become IP packets. The sweep range is "
              "therefore given static neighbour entries pointing at a MAC nobody owns, which is how a routed sweep looks to the sensor "
              "(IP packets leave, nothing answers). ARP-level sweeps are not detected by this sensor.",
              "- **Limits of this evaluation:** one lab, one victim OS, a handful of tools, short benign scenarios. Treat it as a "
              "regression and sanity benchmark, not a statement about production networks."]
    if args.notes and Path(args.notes).exists():
        lines += ["", Path(args.notes).read_text(encoding="utf-8").rstrip()]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    (results / "evaluation.json").write_text(json.dumps(evaluated, indent=2, default=str))
    print(f"\nattacks detected {len(must_hit)}/{len(must)} (+{len(detected) - len(must_hit)} limitation cases), "
          f"benign clean {len(benign) - len(fps)}/{len(benign)}  ->  {args.out}")


if __name__ == "__main__":
    main()
